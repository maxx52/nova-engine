// Disposable localhost deployment only: real database and two browser tabs.
import assert from 'node:assert/strict'
export async function runContentRecoveryChecks(page) {
 const other=await page.context().newPage()
 const nav=p=>p.getByRole('button',{name:/Страницы/}).click()
 const row=p=>p.locator('tbody tr').filter({hasText:'ci-content-recovery'})
 const edit=p=>row(p).getByRole('button',{name:'Изменить',exact:true}).click()
 const field=p=>p.getByLabel('Вступительный текст',{exact:false})
 const save=p=>p.getByRole('button',{name:'Сохранить',exact:true}).click()
 const closed=p=>p.locator('.page-editor-modal').waitFor({state:'hidden'})
 const draft=p=>p.getByRole('status').filter({hasText:'Личный черновик сохранён'}).waitFor()
 const read=()=>page.evaluate(async()=> (await (await fetch('/api/admin/pages')).json()).find(p=>p.slug==='ci-content-recovery'))
 try {
  await nav(page);await page.getByRole('button',{name:'＋ Создать страницу',exact:true}).click()
  await page.getByLabel('Заголовок',{exact:true}).fill('CI recovery')
  // Incomplete slugs are valid private work, but never become public records.
  await page.getByLabel('Адрес страницы',{exact:false}).fill('ещё не готово')
  await field(page).fill('Original recovery text')
  await draft(page)
  assert.equal(await read(),undefined)
  await page.reload();await nav(page);await page.getByRole('button',{name:'＋ Создать страницу',exact:true}).click()
  await page.getByRole('button',{name:'Восстановить личный черновик',exact:true}).click()
  assert.equal(await field(page).inputValue(),'Original recovery text')
  assert.equal(await page.getByLabel('Адрес страницы',{exact:false}).inputValue(),'ещё не готово')
  await page.getByLabel('Адрес страницы',{exact:false}).fill('ci-content-recovery')
  await save(page);await closed(page)
  let server=await read();assert.equal(server.published,false)
  // Both editors start from the same committed version and no private draft.
  await edit(page)
  await other.goto('https://localhost/admin/');await nav(other);await edit(other)
  await field(other).fill('Other editor committed text');await save(other);await closed(other)
  await field(page).fill('My locally recovered text');await draft(page)
  await save(page)
  await page.getByText('На сервере есть изменения другого редактора.',{exact:true}).waitFor()
  assert.equal(await field(page).inputValue(),'My locally recovered text')
  assert.equal((await read()).content,'Other editor committed text')
  await page.getByRole('button',{name:'Продолжить с моим вариантом',exact:true}).click()
  await save(page);await closed(page)
  server=await read();assert.equal(server.content,'My locally recovered text');assert.equal(server.revision,'3')
  await edit(page);await page.getByRole('button',{name:'История версий',exact:true}).click()
  await page.getByRole('button',{name:/^Версия 1 ·/}).click()
  assert.equal(await page.locator('.version-compare iframe,.version-compare script,.version-compare img').count(),0)
  await page.getByRole('button',{name:'Загрузить версию как черновик',exact:true}).click()
  assert.equal(await field(page).inputValue(),'Original recovery text')
  assert.equal((await read()).revision,'3','previewing a historic version performs no write')
  await save(page);await closed(page)
  server=await read();assert.equal(server.revision,'4');assert.equal(server.published,false)
  // Two tabs must also respect CAS for a personal work copy.
  await edit(page);await nav(other);await edit(other)
  await field(page).fill('Private first tab');await draft(page)
  await field(other).fill('Private second tab')
  await other.getByRole('status').filter({hasText:'Личный черновик изменён в другой вкладке'}).waitFor()
  assert.equal(await other.getByRole('button',{name:'Сохранить',exact:true}).isDisabled(),true)
  other.once('dialog',d=>d.accept());await other.getByRole('button',{name:'Отмена',exact:true}).click();await closed(other)
  await save(page);await closed(page)
  await edit(page);await page.getByLabel('Опубликована',{exact:true}).check();await save(page);await closed(page)
  page.once('dialog',d=>d.accept());await row(page).getByRole('button',{name:'В корзину',exact:true}).click()
  await row(page).waitFor({state:'hidden'})
  assert.equal(await page.evaluate(async()=> (await fetch('/api/pages/ci-content-recovery')).status),404)
  await page.getByRole('button',{name:'Корзина',exact:true}).click()
  page.once('dialog',d=>d.accept());await row(page).getByRole('button',{name:'Восстановить',exact:true}).click();await row(page).waitFor({state:'hidden'})
  await page.getByRole('button',{name:'Все страницы',exact:true}).click()
  server=await read();assert.equal(server.published,false)
  page.once('dialog',d=>d.accept());await row(page).getByRole('button',{name:'В корзину',exact:true}).click();await row(page).waitFor({state:'hidden'})
  await page.getByRole('button',{name:'Корзина',exact:true}).click()
  page.once('dialog',d=>d.accept());await row(page).getByRole('button',{name:'Удалить окончательно',exact:true}).click();await row(page).waitFor({state:'hidden'})
  // The article editor uses the same lifecycle, including tags after recovery.
  await page.getByRole('button',{name:/Блог/}).click()
  await page.getByRole('button',{name:'＋ Создать статью',exact:true}).click()
  await page.getByLabel('Заголовок',{exact:true}).fill('CI article recovery')
  await page.getByLabel('Теги через запятую',{exact:false}).fill('Новости, NOVA')
  await page.getByLabel('Текст статьи',{exact:false}).fill('Article recovery text');await draft(page)
  await page.getByRole('button',{name:'Отмена',exact:true}).click()
  await page.locator('.blog-modal').waitFor({state:'hidden'})
  await page.getByRole('button',{name:'＋ Создать статью',exact:true}).click()
  await page.getByRole('button',{name:'Восстановить личный черновик',exact:true}).click()
  assert.equal(await page.getByLabel('Теги через запятую',{exact:false}).inputValue(),'Новости, NOVA')
  await page.getByLabel('Адрес статьи',{exact:false}).fill('ci-article-recovery')
  await save(page);await page.locator('.blog-modal').waitFor({state:'hidden'})
  const article=page.locator('tbody tr').filter({hasText:'ci-article-recovery'})
  await article.getByRole('button',{name:'Изменить',exact:true}).click()
  await page.getByRole('button',{name:'История версий',exact:true}).click()
  await page.getByRole('button',{name:/^Версия 1 ·/}).waitFor()
  await page.getByRole('button',{name:'Отмена',exact:true}).click()
  console.log('PASS content recovery UI: incomplete draft survives reload; recovery, two-tab content and work-copy conflicts, version comparison, draft restoration, trash/purge and article tag recovery')
 }finally{await other.close()}
}
