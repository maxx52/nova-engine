// Disposable localhost production deployment only.
import assert from 'node:assert/strict'
export async function runSeoChecks(page){
 await page.setViewportSize({width:1280,height:900})
 await page.getByRole('button',{name:/Страницы/}).click()
 await page.getByRole('button',{name:'＋ Создать страницу',exact:true}).click()
 await page.getByLabel('Заголовок',{exact:true}).fill('CI SEO page')
 await page.getByLabel('Адрес страницы',{exact:false}).fill('ci-seo-page')
 await page.getByText('SEO и предпросмотр ссылки',{exact:true}).click()
 await page.getByLabel('SEO-заголовок',{exact:true}).fill('CI unique SEO title')
 await page.getByLabel('Метаописание',{exact:true}).fill('CI unique meta description')
 await page.getByLabel('Опубликована',{exact:true}).check()
 await page.getByRole('button',{name:'Сохранить',exact:true}).click()
 await page.getByRole('cell',{name:'CI SEO page',exact:true}).waitFor()
 const request=page.context().request
 const initial=await request.get('https://localhost/ci-seo-page');assert.equal(initial.status(),200);const html=await initial.text()
 assert.ok(html.includes('<title>CI unique SEO title</title>'));assert.ok(html.includes('content="CI unique meta description"'))
 assert.ok(html.includes('href="https://localhost/ci-seo-page"'));assert.ok(html.includes('application/ld+json'))
 assert.equal((await request.get('https://localhost/absent-ci-page')).status(),404)
 const robots=await request.get('https://localhost/robots.txt');assert.ok((await robots.text()).includes('Sitemap: https://localhost/sitemap.xml'))
 const sitemap=await request.get('https://localhost/sitemap-1.xml');assert.ok((await sitemap.text()).includes('https://localhost/ci-seo-page'))
 await page.getByRole('button',{name:/Товары/}).click()
 await page.getByRole('button',{name:'Изменить',exact:true}).first().click()
 await page.getByText('SEO и предпросмотр ссылки',{exact:true}).click()
 await page.getByLabel('SEO-заголовок',{exact:true}).fill('CI Product SEO')
 await page.getByRole('button',{name:'Сохранить',exact:true}).click()
 await page.locator('.modal-backdrop').waitFor({state:'hidden'})
 const product=await request.get('https://localhost/product/1');assert.equal(product.status(),200);const productHtml=await product.text();assert.ok(productHtml.includes('<title>CI Product SEO</title>'))
 const graph=JSON.parse(productHtml.match(/<script type="application\/ld\+json"[^>]*>([\s\S]*?)<\/script>/)[1]);assert.ok(graph['@graph'].some(n=>n['@type']==='Product'))
 await page.getByRole('button',{name:/SEO и редиректы/}).click()
 await page.getByLabel('Описание сайта по умолчанию',{exact:true}).fill('Unsaved SEO settings must survive redirect creation')
 await page.getByLabel('Старый адрес',{exact:true}).fill('/ci-old-page')
 await page.getByLabel('Новый адрес',{exact:true}).fill('/ci-seo-page')
 await page.getByRole('button',{name:'Добавить редирект',exact:true}).click()
 await page.getByRole('cell',{name:'/ci-old-page',exact:true}).waitFor()
 assert.equal(await page.getByLabel('Описание сайта по умолчанию',{exact:true}).inputValue(),'Unsaved SEO settings must survive redirect creation')
 const redirect=await request.get('https://localhost/ci-old-page',{maxRedirects:0});assert.equal(redirect.status(),301);assert.equal(redirect.headers().location,'/ci-seo-page')
 const publicPage=await page.context().newPage()
 try{
  await publicPage.goto('https://localhost/catalog')
  await publicPage.locator('.product-card').first().waitFor()
  await publicPage.locator('a[href="/product/1"]').first().click()
  await publicPage.waitForFunction(()=>document.title==='CI Product SEO')
  assert.equal(await publicPage.locator('link[rel=canonical]').count(),1)
  assert.equal(await publicPage.locator('link[rel=canonical]').getAttribute('href'),'https://localhost/product/1')
  await publicPage.locator('.detail-back').click()
  await publicPage.waitForFunction(()=>!document.title.includes('CI Product SEO')&&document.querySelector('link[rel=canonical]')?.href==='https://localhost/catalog')
  assert.ok(!(await publicPage.locator('script[type="application/ld+json"]').textContent()).includes('"@type":"Product"'))
 }finally{await publicPage.close()}
 console.log('PASS SEO UI: page and product metadata in initial HTML, canonical, JSON-LD, robots, sitemap, HTTP 301 and 404, SPA metadata transitions')
}
