// Disposable localhost deployment only. No provider keys or real notifications.
import assert from 'node:assert/strict'
export async function runOrderOperationsChecks(page){
 await page.getByRole('button',{name:/Доставка и уведомления/}).click()
 await page.getByRole('heading',{name:'Способы получения',exact:true}).waitFor()
 const delivery=page.locator('.fulfillment article').nth(1)
 await delivery.getByLabel('Стоимость, ₽',{exact:true}).fill('350')
 await delivery.getByLabel('Бесплатно от суммы товаров, ₽',{exact:true}).fill('5000')
 await page.getByRole('button',{name:'Сохранить доставку и уведомления',exact:true}).click()
 await page.getByText('Настройки сохранены',{exact:true}).waitFor()
 const shipping=await (await page.context().request.get('https://localhost/api/shipping')).json();assert.equal(shipping.options[1].price_cents,35000);assert.equal(shipping.options[1].free_from_cents,500000)
 await page.getByRole('button',{name:/^.*Оплата$/}).click()
 await page.getByRole('heading',{name:'Автоматическое подтверждение оплаты',exact:true}).waitFor()
 assert.equal(await page.getByLabel('Секретный ключ / API Secret',{exact:true}).inputValue(),'')
 await page.locator('.automatic select').selectOption('cloudpayments')
 await page.getByText('https://localhost/api/payments/webhooks/cloudpayments/check',{exact:true}).waitFor()
 // Prepare an isolated product through the authenticated API, not production SQL.
 const product=await page.evaluate(async()=>{
  const {csrf_token}=await (await fetch('/api/auth/me')).json()
  const r=await fetch('/api/products',{method:'POST',headers:{'content-type':'application/json','x-nova-request':'1','x-csrf-token':csrf_token},body:JSON.stringify({name:'CI shipping product',category:'Другое',price:100,stock:5,description:'Disposable order fixture',published:true})})
  if(!r.ok)throw Error('Fixture product failed: '+r.status);return r.json()
 })
 const publicPage=await page.context().newPage();let receipt
 try{
  await publicPage.goto('https://localhost/product/'+product.id)
  await publicPage.locator('.detail-info>.primary-button').click()
  await publicPage.locator('.cart-trigger').click()
  await publicPage.locator('.drawer-bottom .primary-button').click()
  await publicPage.getByLabel('Имя',{exact:true}).fill('CI shipping buyer')
  await publicPage.getByLabel('Телефон',{exact:true}).fill('+79991112233')
  await publicPage.getByLabel('Электронная почта (необязательно)',{exact:true}).fill('ci@example.invalid')
  await publicPage.getByLabel('Способ получения',{exact:false}).selectOption('delivery')
  await publicPage.getByLabel('Адрес доставки',{exact:true}).fill('CI disposable address')
  await publicPage.getByLabel('Получать уведомления о заказе на email',{exact:true}).check()
  const statusResponse=publicPage.waitForResponse(r=>r.url().endsWith('/api/orders/status')&&r.request().method()==='POST')
  const response=publicPage.waitForResponse(r=>r.url().endsWith('/api/orders')&&r.request().method()==='POST')
  await publicPage.getByRole('button',{name:'Отправить заказ',exact:true}).click()
  const r=await response;assert.equal(r.status(),201);receipt=await r.json();assert.equal(receipt.total_cents,45000)
  const initialStatus=await statusResponse;assert.equal(initialStatus.status(),200,await initialStatus.text());assert.equal((await initialStatus.json()).number,receipt.number)
  await publicPage.getByRole('heading',{name:'Заказ принят',exact:true}).waitFor()
  await publicPage.getByRole('heading',{name:'Статус заказа '+receipt.number,exact:true}).waitFor()
  const href=await publicPage.getByRole('link',{name:'Ссылка на статус заказа',exact:true}).getAttribute('href');assert.ok(href.includes('#token='))
  await publicPage.goto('https://localhost'+href)
  await publicPage.getByRole('heading',{name:'Статус заказа '+receipt.number,exact:true}).waitFor()
  await publicPage.waitForFunction(()=>document.querySelector('meta[name=robots]')?.content==='noindex, nofollow')
  assert.equal(await publicPage.locator('body').textContent().then(s=>s.includes('CI disposable address')),false)
 }finally{await publicPage.close()}
 await page.getByRole('button',{name:/Заказы/}).click()
 const row=page.getByRole('row').filter({hasText:receipt.number})
 await row.getByRole('button',{name:'Открыть заказ',exact:true}).click()
 await page.getByRole('heading',{name:'Отправление',exact:true}).waitFor()
 await page.getByLabel('Трек-номер',{exact:true}).fill('CI-TRACK-1')
 await page.getByLabel('HTTPS-ссылка отслеживания',{exact:true}).fill('https://tracking.example.ru/ci')
 await page.getByRole('button',{name:'Сохранить отправление',exact:true}).click()
 await page.waitForFunction(()=>!document.querySelector('.commerce-modal fieldset')?.disabled)
 await page.getByLabel('Статус',{exact:true}).selectOption('confirmed')
 await page.getByRole('button',{name:'Сохранить заказ',exact:true}).click()
 await page.waitForFunction(()=>!document.querySelector('.commerce-modal fieldset')?.disabled)
 const status=await page.context().request.post('https://localhost/api/orders/status',{headers:{'x-nova-checkout':'1'},data:{token:receipt.status_token}});assert.equal(status.status(),200);const details=await status.json();assert.equal(details.status,'confirmed');assert.equal(details.tracking_code,'CI-TRACK-1');assert.equal(details.total_cents,45000)
 await page.getByRole('button',{name:'Закрыть заказ',exact:true}).click()
 console.log('PASS order UI: shipping tariffs, automatic payment setup, checkout total with delivery, opt-in, private status page, tracking and status processing')
}
